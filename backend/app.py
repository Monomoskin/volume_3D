# --- 2. UTILITY FUNCTIONS ---

def load_data_log():
    """Loads the log file (CSV) or creates an empty DataFrame."""
    if os.path.exists(LOG_FILE) and os.path.getsize(LOG_FILE) > 0:
        try:
            return pd.read_csv(LOG_FILE)
        except pd.errors.EmptyDataError:
            print("Warning: data_log.csv is empty.")
            pass
    
    # If the file does not exist, is empty, or reading fails, create the empty DataFrame
    return pd.DataFrame(columns=['Cell Name', 'Measurement ID', 'Upload Date', 'Estimated Volume (mL)', 'Image Location (Top)', 'Image Location (Side)'])

def get_image_urls_from_path(row):
    """
    Converts the local file paths saved in the CSV to URLs accessible by the frontend.
    It reconstructs the URL based on the date/cell/filename convention.
    """
    try:
        # Extract the date string from the 'Upload Date' column
        date_str = datetime.strptime(row['Upload Date'].split(' ')[0], "%Y-%m-%d").strftime("%Y-%m-%d")
        
        # Predicted filenames generated by predict.py
        top_filename = f"{row['Cell Name']}_TOP_predicted.jpg"
        side_filename = f"{row['Cell Name']}_SIDE_predicted.jpg"

        # The relative path is: Date/Cell_Name/File_Name
        base_url_path = os.path.join(date_str, row['Cell Name'])

        return {
            'predicted_image_top_url': f"http://localhost:5000/api/predicted_images/{os.path.join(base_url_path, top_filename)}",
            'predicted_image_side_url': f"http://localhost:5000/api/predicted_images/{os.path.join(base_url_path, side_filename)}",
        }
    except Exception as e:
        print(f"Error reconstructing URLs for row {row['Measurement ID']}: {e}")
        return {
            'predicted_image_top_url': None,
            'predicted_image_side_url': None,
        }


