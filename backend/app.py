@app.route('/api/estimations/<string:cell_name>', methods=['GET'])
def get_cell_history(cell_name):
    """Gets the estimation history for a specific cell."""
    df = load_data_log()
    if df.empty:
        return jsonify({"message": "No estimations recorded."}), 404

    # Filter by cell name
    cell_data = df[df['Cell Name'] == cell_name]
    
    if cell_data.empty:
        return jsonify({"message": f"No estimations found for cell: {cell_name}"}), 404

    # Select columns and sort by date (oldest first for history timeline)
    cell_data = cell_data.sort_values(by='Upload Date', ascending=True)
    
    df_output = cell_data[['Cell Name', 'Measurement ID', 'Upload Date', 'Estimated Volume (mL)']]
    
    # Add image URLs
    df_output[['predicted_image_top_url', 'predicted_image_side_url']] = cell_data.apply(get_image_urls_from_path, axis=1, result_type='expand')

    results = df_output.to_dict(orient='records')

    return jsonify(results), 200


