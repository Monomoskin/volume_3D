@app.route('/api/estimations', methods=['GET'])
def list_estimations():
    """Lists all performed estimations."""
    df = load_data_log()
    if df.empty:
        return jsonify({"message": "No estimations recorded."}), 404

    # Select only the columns we want to expose
    df_output = df[['Cell Name', 'Measurement ID', 'Upload Date', 'Estimated Volume (mL)']]
    
    # Add image URLs
    df_output[['predicted_image_top_url', 'predicted_image_side_url']] = df.apply(get_image_urls_from_path, axis=1, result_type='expand')

    # Convert DataFrame to JSON, sorted by upload date (most recent first)
    results = df_output.sort_values(by='Upload Date', ascending=False).to_dict(orient='records')
    
    return jsonify(results), 200

@app.route('/api/estimations/summary', methods=['GET'])
def get_estimations_summary():
    """
    Devuelve un resumen de las estimaciones por célula, incluyendo:
    - Última estimación
    - Cantidad de veces estimada
    - Valor de la última estimación
    - Fecha de la última estimación
    """
    df = load_data_log()
    if df.empty:
        return jsonify([]), 200 # Devolvemos un array vacío si no hay datos

    # Aseguramos que la columna de fecha sea un objeto datetime para la comparación
    df['Upload Date'] = pd.to_datetime(df['Upload Date'])
    
    # 1. Encontrar la última estimación por célula
    # Ordenamos por fecha descendente y tomamos el primer registro de cada grupo ('Cell Name')
    last_estimation = df.sort_values(by='Upload Date', ascending=False).drop_duplicates(subset=['Cell Name'], keep='first')

    # 2. Calcular la cantidad total de mediciones por célula
    count_estimations = df.groupby('Cell Name')['Measurement ID'].count().reset_index()
    count_estimations = count_estimations.rename(columns={'Measurement ID': 'Estimated Count'})

    # 3. Combinar los resultados
    # Seleccionamos las columnas clave de la última medición
    summary = last_estimation[['Cell Name', 'Estimated Volume (mL)', 'Upload Date', 'Measurement ID']].copy()
    
    # Renombrar columnas para claridad en la respuesta JSON
    summary.rename(columns={
        'Estimated Volume (mL)': 'Last Estimated Volume (mL)',
        'Upload Date': 'Last Estimation Date',
        'Measurement ID': 'Last Measurement ID'
    }, inplace=True)

    # Fusionar con el conteo de estimaciones
    summary = pd.merge(summary, count_estimations, on='Cell Name', how='left')

    # 4. Añadir las URLs de imagen para la última medición
    # Usamos la función existente para obtener las URLs
    summary[['predicted_image_top_url', 'predicted_image_side_url']] = summary.apply(get_image_urls_from_path, axis=1, result_type='expand')

    # 5. Formatear la fecha para la respuesta JSON
    summary['Last Estimation Date'] = summary['Last Estimation Date'].dt.strftime("%Y-%m-%d %H:%M:%S")

    # Convertir el DataFrame a una lista de diccionarios (JSON)
    results = summary.to_dict(orient='records')
    
    return jsonify(results), 200

